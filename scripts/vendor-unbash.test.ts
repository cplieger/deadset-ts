import { readdirSync, readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { needed, vendored } from "./vendor-unbash.ts";

const DIR = new URL("../src/vendor/unbash/", import.meta.url);

/** The two lines `vendored` puts before an upstream file. */
const HEADER =
  /^\/\/ Code generated by scripts\/vendor-unbash\.ts from unbash 6\.0\.0 \(968c14992a43dc06ce29c9f51858abd4a87851ea\)\. DO NOT EDIT\.\n\/\/ @ts-nocheck\n/u;

describe("the vendored unbash copy", () => {
  const names = readdirSync(DIR).filter((name) => name.endsWith(".ts"));
  const upstream = (name: string): string =>
    readFileSync(new URL(name, DIR), "utf8").replace(HEADER, "");

  it.each(names)("puts the generated header and nothing else before upstream's %s", (name) => {
    const text = readFileSync(new URL(name, DIR), "utf8");

    expect(text).toMatch(HEADER);
    expect(vendored(upstream(name), "6.0.0 (968c14992a43dc06ce29c9f51858abd4a87851ea)")).toBe(text);
  });

  it("holds exactly the files parser.ts reaches, with upstream's license and its record", () => {
    expect(needed(upstream)).toEqual([...names].sort());
    expect(
      readdirSync(DIR)
        .filter((name) => !name.endsWith(".ts"))
        .sort(),
    ).toEqual(["LICENSE", "VENDORED.md"]);
  });
});

describe("needed", () => {
  it("follows relative imports from the entry once each, and no other import", () => {
    const files: Readonly<Record<string, string>> = {
      "parser.ts":
        'import { a } from "./a.ts";\nimport x from "node:fs";\nexport * from "./b.ts";\n',
      "a.ts": 'import type { B } from "./b.ts";\n',
      "b.ts": 'import { a } from "./a.ts";\n',
      "unused.ts": "",
    };

    expect(needed((name) => files[name] ?? "")).toEqual(["a.ts", "b.ts", "parser.ts"]);
  });
});
