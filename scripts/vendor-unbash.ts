import { execFileSync } from "node:child_process";
import { copyFileSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Writes `src/vendor/unbash/` from a checkout of https://github.com/webpro-nl/unbash: the
 * files its `parse` needs, each with the two lines {@link vendored} puts first, and its
 * LICENSE. Run it with `npm run vendor -- <checkout>`; `VENDORED.md` beside the copy names
 * the commit and every edit.
 */

const ROOT = resolve(fileURLToPath(new URL(".", import.meta.url)), "..");

/** The copy's directory, relative to the repository root. */
const VENDOR_DIR = "src/vendor/unbash";

const RELATIVE_IMPORT = /\bfrom\s+"\.\/([^"]+)"/gu;

/** The files below one source directory that `entry` reaches by its relative imports, sorted. */
export function needed(read: (name: string) => string, entry = "parser.ts"): readonly string[] {
  const found = new Set<string>();
  const pending = [entry];
  for (let name = pending.pop(); name !== undefined; name = pending.pop()) {
    if (!found.has(name)) {
      found.add(name);
      pending.push(...[...read(name).matchAll(RELATIVE_IMPORT)].flatMap((match) => match[1] ?? []));
    }
  }
  return [...found].sort();
}

/**
 * One upstream file as the copy holds it. The header line marks it generated, so the
 * dead-code self-check retains it, and `@ts-nocheck` leaves it to upstream's own checks,
 * which do not enable this repository's stricter compiler options.
 */
export function vendored(text: string, release: string): string {
  return `// Code generated by scripts/vendor-unbash.ts from unbash ${release}. DO NOT EDIT.\n// @ts-nocheck\n${text}`;
}

function main(checkout: string): void {
  const source = join(checkout, "src");
  const version = (
    JSON.parse(readFileSync(join(checkout, "package.json"), "utf8")) as {
      readonly version: string;
    }
  ).version;
  const commit = execFileSync("git", ["-C", checkout, "rev-parse", "HEAD"], {
    encoding: "utf8",
  }).trim();
  const target = join(ROOT, VENDOR_DIR);
  mkdirSync(target, { recursive: true });
  for (const name of readdirSync(target).filter((one) => one.endsWith(".ts"))) {
    rmSync(join(target, name));
  }
  const read = (name: string): string => readFileSync(join(source, name), "utf8");
  for (const name of needed(read)) {
    writeFileSync(join(target, name), vendored(read(name), `${version} (${commit})`));
  }
  copyFileSync(join(checkout, "LICENSE"), join(target, "LICENSE"));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const checkout = process.argv[2];
  if (checkout === undefined) {
    throw new Error("usage: node scripts/vendor-unbash.ts <unbash checkout>");
  }
  main(checkout);
}
