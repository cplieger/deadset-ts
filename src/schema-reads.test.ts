/**
 * The facts document one analysis of a written target publishes, by record symbol
 * fragment; a target `missing` a package notes only the type errors that leaves, and the
 * compiler server panics on the questions `panicsOn` names, by accessor and `<file>:<pos>`.
 */
function factsOf(
  files: Readonly<Record<string, string>>,
  minConfidence = "possible",
  missing?: string,
  panicsOn?: (accessor: string, locations: readonly string[]) => boolean,
): Readonly<Record<string, string>> {
  const root = writeProject({
    "deadset.json": JSON.stringify({
      target: { kind: "application" },
      analysis: { min_confidence: minConfidence },
      ts: { entry_files: ["src/main.ts"] },
    }),
    "package.json": '{ "name": "@example/app", "private": true, "type": "module" }\n',
    "tsconfig.json": TSCONFIG,
    ...files,
  });
  const dir = mkdtempSync(join(tmpdir(), "deadset-ts-schema-reads-"));
  onTestFinished(() => {
    rmSync(root, { recursive: true, force: true });
    rmSync(dir, { recursive: true, force: true });
  });
  const err = new MemoryWriter();
  run(
    [
      "analyze",
      `--target=${root}`,
      `--report=${join(dir, "report.json")}`,
      `--facts=${join(dir, "facts.json")}`,
    ],
    new MemoryWriter(),
    err,
    { ...nodeHost(), workingDirectory: () => root, analyzerVersion: () => "0.0.0" },
    (options: EngineOptions): Engine => {
      const opened = openEngine(options);
      return {
        ...opened,
        ask: (accessor, locations, question) => {
          if (panicsOn?.(accessor, locations()) === true) {
            throw new Error(`panic: ${accessor}`);
          }
          return opened.ask(accessor, locations, question);
        },
      };
    },
  );
  const notes = err.text.split("\n").filter((line) => line !== "");
  const failed = (line: string): boolean =>
    /^deadset-ts: the checker answered \d+ questions? with a failure /u.test(line);
  const unresolved = (line: string): boolean =>
    missing !== undefined && line.includes(`Cannot find module '${missing}`);
  expect(notes.filter(failed)).toHaveLength(panicsOn === undefined ? 0 : 1);
  if (missing !== undefined) {
    expect(notes.some(unresolved)).toBe(true);
  }
  expect(notes.filter((line) => !failed(line) && !unresolved(line))).toEqual([]);
  const document = JSON.parse(readFileSync(join(dir, "facts.json"), "utf8")) as {
    readonly bindings: readonly {
      readonly role: string;
      readonly symbol: string;
      readonly state?: string;
      readonly cap?: string;
    }[];
  };
  return Object.fromEntries(
    document.bindings
      .filter((one) => one.role === "consumer")
      .map((one) => [
        one.symbol.slice(one.symbol.indexOf("#") + 1),
        [one.state, one.cap].filter((part) => part !== undefined).join(" "),
      ]),
  );
}

