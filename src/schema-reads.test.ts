/** The facts of a v2 target whose one hand-written file is `main`, with the runtime unless `runtime` is false. */
function v2(
  main: string,
  minConfidence?: string,
  runtime = true,
): Readonly<Record<string, string>> {
  return factsOf(
    {
      ...(runtime ? RUNTIME_V2 : {}),
      "src/gen/v1/a_pb.ts": GENERATED_V2,
      "src/gen/v1/b_pb.ts": GENERATED_V2_B,
      "src/main.ts": main,
    },
    minConfidence,
    runtime ? undefined : "@bufbuild/protobuf",
  );
}

/** The target and installed files of one corpus fixture's TypeScript rendering, as a project's files. */
function renderingOf(fixture: string): Record<string, string> {
  const root = fileURLToPath(new URL(`../fixtures/corpus/${fixture}/ts/`, import.meta.url));
  const files: Record<string, string> = {};
  for (const [part, below] of [
    ["target", ""],
    ["installed", "node_modules/"],
  ] as const) {
    for (const entry of readdirSync(join(root, part), { recursive: true, withFileTypes: true })) {
      if (entry.isFile()) {
        const at = relative(join(root, part), join(entry.parentPath, entry.name));
        files[`${below}${at.split(sep).join("/")}`] = readFileSync(
          join(entry.parentPath, entry.name),
          "utf8",
        );
      }
    }
  }
  return files;
}

/** The fields the schema reader itself counts as written in a target, by record symbol fragment. */
function readerWrites(files: Readonly<Record<string, string>>): readonly string[] {
  const root = writeProject({
    "package.json": '{ "name": "@example/app", "private": true, "type": "module" }\n',
    "tsconfig.json": TSCONFIG,
    ...files,
  });
  onTestFinished(() => {
    rmSync(root, { recursive: true, force: true });
  });
  const { config } = resolve({
    repository: {
      text: JSON.stringify({
        target: { kind: "application" },
        analysis: { min_confidence: "possible" },
        ts: { entry_files: ["src/main.ts"] },
      }),
      label: "deadset.json",
    },
  });
  const host = nodeHost();
  const read = readEmitterRun(
    openEngine({ collectTiming: false }),
    host,
    scopeForDir(host, root),
    config,
    { production: true },
    DETECTORS,
  );
  return read.projects.flatMap((project) => {
    const fragments = new Map(
      project.configured.symbols.map((one) => [one.id, one.ref.slice(one.ref.indexOf("#") + 1)]),
    );
    return project.schema.written.map((id) => fragments.get(id) ?? id);
  });
}

describe("the schema reads of ts-proto hand code", () => {
  it(
    "gives descriptor-exposure where hand code encodes a file's protoMetadata descriptor, and none for another use of it",
    () => {
      const files = renderingOf("proto-ts-proto-message-fns");
      const descriptors = {
        "node_modules/ts-proto-descriptors/index.d.ts": [
          "export type FileDescriptorProto = any;",
          "export declare const FileDescriptorProto: { encode(message: unknown): { finish(): Uint8Array }; fromPartial(object: unknown): unknown };",
          "",
        ].join("\n"),
      };
      const at = (main: string): Readonly<Record<string, string>> =>
        factsOf({ ...files, ...descriptors, "src/main.ts": main });
      const encoded = (argument: string): string =>
        [
          'import { FileDescriptorProto } from "ts-proto-descriptors";',
          'import { protoMetadata } from "./gen/v1/service.js";',
          `console.log(FileDescriptorProto.encode(${argument}).finish().length);`,
          "",
        ].join("\n");
      for (const argument of [
        "protoMetadata.fileDescriptor",
        "FileDescriptorProto.fromPartial(protoMetadata.fileDescriptor)",
      ]) {
        expect(at(encoded(argument))).toMatchObject({
          "PingRequest.number": "unreferenced descriptor-exposure",
        });
      }
      expect(
        factsOf(
          {
            ...Object.fromEntries(
              Object.entries(files).filter(
                ([path]) => !path.startsWith("node_modules/ts-proto-descriptors/"),
              ),
            ),
            // A declared dependency that is not installed ends the run as missing-module.
            "package.json": JSON.stringify({
              name: "@example/target",
              private: true,
              type: "module",
              dependencies: { "@bufbuild/protobuf": "2.16.0" },
            }),
            "src/main.ts": encoded("protoMetadata.fileDescriptor"),
          },
          "possible",
          "ts-proto-descriptors",
        ),
      ).toMatchObject({ "PingRequest.number": "unreferenced descriptor-exposure" });
      expect(
        at(
          [
            'import { protoMetadata } from "./gen/v1/service.js";',
            "console.log(Object.keys(protoMetadata.references).length);",
            "",
          ].join("\n"),
        ),
      ).toMatchObject({ "PingRequest.number": "unreferenced" });
    },
    LOAD_TIMEOUT * 4,
  );

  it(
    "reads every field a message function encodes where the checker does not answer for its receiver",
    () => {
      const main = [
        'import { PingRequest } from "./gen/v1/service.js";',
        "declare const request: PingRequest;",
        "console.log(PingRequest.encode(request).finish().length);",
        "",
      ].join("\n");
      const at = `/src/main.ts:${String(main.lastIndexOf("console.log(") + "console.log(".length)}`;
      const facts = factsOf(
        { ...renderingOf("proto-ts-proto-message-fns"), "src/main.ts": main },
        "possible",
        undefined,
        (accessor, locations) =>
          accessor === "getSymbolAtLocation" && locations.some((one) => one.endsWith(at)),
      );
      expect(facts).toMatchObject({ "PingRequest.number": "live" });
    },
    LOAD_TIMEOUT,
  );

  it(
    "reads every field a message function encodes where it is called with no receiver, by its resolved signature",
    () => {
      const facts = factsOf({
        ...renderingOf("proto-ts-proto-message-fns"),
        "src/main.ts": [
          'import { PingRequest } from "./gen/v1/service.js";',
          "const { encode } = PingRequest;",
          "declare const request: PingRequest;",
          "console.log(encode(request).finish().length);",
          "",
        ].join("\n"),
      });
      expect(facts).toMatchObject({ "PingRequest.number": "live" });
    },
    LOAD_TIMEOUT,
  );

  it(
    "reads no field a message function writes where it is called with no receiver, its message named by the signature's return type",
    () => {
      for (const [bound, call] of [
        ["const { fromPartial } = PingRequest;", "fromPartial({ number: 1 })"],
        ["const { decode } = PingRequest;", "decode(new Uint8Array())"],
      ]) {
        const facts = factsOf({
          ...renderingOf("proto-ts-proto-message-fns"),
          "src/main.ts": [
            'import { PingRequest } from "./gen/v1/service.js";',
            bound,
            `console.log(${call} === undefined);`,
            "",
          ].join("\n"),
        });
        expect(facts, call).toMatchObject({
          "PingRequest.number": "unreferenced",
          "PingRequest.text": "unreferenced",
          "PingResponse.number": "unreferenced",
        });
      }
    },
    LOAD_TIMEOUT * 2,
  );

  it(
    "writes the fields of the message a receiver-less decode's signature returns, and none of another message's",
    () => {
      const written = readerWrites({
        ...renderingOf("proto-ts-proto-message-fns"),
        "src/main.ts": [
          'import { PingRequest } from "./gen/v1/service.js";',
          "const { decode } = PingRequest;",
          "console.log(decode(new Uint8Array()) === undefined);",
          "",
        ].join("\n"),
      });
      expect([...written].sort()).toEqual(["PingRequest.number", "PingRequest.text"]);
    },
    LOAD_TIMEOUT,
  );
});

