/**
 * The generated-file class on TypeScript: every declaration in a file that marks itself
 * generated, below a directory an applied convention row names as generated, or minified,
 * is retained, because a generator owns the file and a deletion there is undone at the next
 * generation. The same decision is each `generated` entry of the facts document.
 */

import {
  isIdentifier,
  isImportDeclaration,
  isPropertyAssignment,
  isStringLiteralLikeNode,
  isVariableStatement,
  NodeFlags,
  type Node,
  type SourceFile,
} from "@typescript/native/ast";
import { GENERATORS } from "./contract/contract.generated.ts";
import type { DetectorInput, Evidence } from "./exempt.ts";
import { minifiedBy } from "./javascript-file.ts";
import type { SourceFiles } from "./source-files.ts";
import { bytewise } from "./text/compare.ts";
import { satisfies } from "./version-range.ts";

/** The generated-code header, matched against each line of a leading comment. */
const HEADER_LINE = /^\/\/ Code generated .* DO NOT EDIT\.$/u;

/** The documentation tag `@generated` as a word of a comment. */
const GENERATED_TAG = /(?<![\w@$])@generated(?![\w$-])/u;

/** A first comment naming the tool that wrote the file. */
const GENERATED_BY = /^\/\/ Generated by \S/u;

/** The word a generator's notice holds, beside one of {@link KEEP_OUT}. */
const GENERATED_WORD = /\bgenerated\b/iu;

/** The phrases a generator's notice asks a reader not to edit the file by. */
const KEEP_OUT = /\b(?:do not edit|will be overwritten|should not make any changes)\b/iu;

/** What decided a file generated, as the facts document's `evidence` names it. */
type GeneratedEvidence = "header" | "tag" | "notice" | "convention" | "minified";

/** The generator row one generated file matches, with the version and the schema files its output states. */
interface GeneratorMatch {
  readonly row: string;
  readonly version?: string;
  readonly schemaFiles: readonly string[];
}

/** Why one file is generated, and which generator wrote it. */
export interface GeneratedFact {
  readonly evidence: GeneratedEvidence;
  /** The 1-based line of the comment line that marks the file; 1 for a row or a minified file. */
  readonly line: number;
  /** The marking line's text, the convention row's name, or what decided the file minified. */
  readonly detail: string;
  readonly generator?: GeneratorMatch;
}

/** One line of a leading comment, with its 1-based line in the file. */
interface CommentLine {
  readonly text: string;
  readonly line: number;
}

/** The comments before a text's first token, a leading hashbang line skipped, each as its lines. */
function leadingComments(text: string): readonly (readonly CommentLine[])[] {
  const comments: CommentLine[][] = [];
  const lineAt = (offset: number): number =>
    text.slice(0, offset).split(/\r\n|[\n\r\u2028\u2029]/u).length;
  const lines = (from: number, to: number): CommentLine[] => {
    const first = lineAt(from);
    return text
      .slice(from, to)
      .split(/\r\n|[\n\r\u2028\u2029]/u)
      .map((one, index) => ({ text: one, line: first + index }));
  };
  let at = text.startsWith("\uFEFF") ? 1 : 0;
  if (text.startsWith("#!", at)) {
    const end = text.indexOf("\n", at);
    at = end === -1 ? text.length : end + 1;
  }
  for (;;) {
    while (at < text.length && /\s/u.test(text.charAt(at))) {
      at++;
    }
    if (text.startsWith("//", at)) {
      const end = text.slice(at).search(/[\r\n\u2028\u2029]/u);
      const stop = end === -1 ? text.length : at + end;
      comments.push(lines(at, stop));
      at = stop;
    } else if (text.startsWith("/*", at)) {
      const end = text.indexOf("*/", at + 2);
      if (end === -1) {
        return comments;
      }
      comments.push(lines(at, end + 2));
      at = end + 2;
    } else {
      return comments;
    }
  }
}

/** The mark one file's leading comments make it generated by, or undefined where they mark nothing. */
export function generatedMark(text: string): Omit<GeneratedFact, "generator"> | undefined {
  const lines = leadingComments(text).flat();
  const header = lines.find((one) => HEADER_LINE.test(one.text));
  if (header !== undefined) {
    return { evidence: "header", line: header.line, detail: header.text };
  }
  const tag = lines.find((one) => GENERATED_TAG.test(one.text));
  if (tag !== undefined) {
    return { evidence: "tag", line: tag.line, detail: tag.text };
  }
  const [first] = lines;
  if (first !== undefined && GENERATED_BY.test(first.text)) {
    return { evidence: "notice", line: first.line, detail: first.text };
  }
  const notice = lines.map((one) => one.text).join("\n");
  if (GENERATED_WORD.test(notice) && KEEP_OUT.test(notice)) {
    const marked = lines.find((one) => GENERATED_WORD.test(one.text) || KEEP_OUT.test(one.text));
    return marked === undefined
      ? undefined
      : { evidence: "notice", line: marked.line, detail: marked.text };
  }
  return undefined;
}

/** What one form's first group captures, for each line the form matches. */
function after(lines: readonly CommentLine[], form: RegExp): readonly string[] {
  return lines.flatMap((one) => form.exec(one.text)?.[1] ?? []);
}

/**
 * Where each plugin's output states its version and its schema files, as `references-ts.36`
 * states: a plugin missing here states no version, and one with no schema form names none.
 */
const STATEMENTS: Readonly<Record<string, { version?: RegExp; schemaFiles?: RegExp }>> = {
  "protoc-gen-es": {
    version: /^\/\/ @generated by protoc-gen-es (\S+)/u,
    schemaFiles: /^\/\/ @generated from file (\S+)/u,
  },
  "protoc-gen-connect-es": {
    version: /^\/\/ @generated by protoc-gen-connect-es (\S+)/u,
    schemaFiles: /^\/\/ @generated from file (\S+)/u,
  },
  "protobuf-ts": {
    version: /^\/\/ @generated by protobuf-ts (\S+)/u,
    schemaFiles: /^\/\/ @generated from protobuf file "([^"]+)"/u,
  },
  "ts-proto": {
    version: /^\/\/\s+protoc-gen-ts_proto\s+(\S+)$/u,
    schemaFiles: /^\/\/ source: (.+)$/u,
  },
  "protoc-gen-grpc-web": {
    version: /^\/\/\s+protoc-gen-grpc-web\s+(\S+)$/u,
    schemaFiles: /^\/\/ source: (.+)$/u,
  },
  "protoc-gen-js": { schemaFiles: /^\/\/ source: (.+)$/u },
  "ts-protoc-gen": { schemaFiles: /^\/\/ file: (.+)$/u },
};

/** A ts-proto service path literal: `/<package>.<service>/<method>`. */
const SERVICE_PATH = /^\/(?:\w+\.)+\w+\/\w+$/u;

/** Whether one ts-proto file writes a service path, as `references-ts.36` reads one. */
function writesServicePath(file: SourceFile): boolean {
  const named = file.statements.some(
    (statement) =>
      isVariableStatement(statement) &&
      (statement.declarationList.flags & NodeFlags.Const) !== 0 &&
      statement.declarationList.declarations.some(
        (one) =>
          isIdentifier(one.name) &&
          one.name.text.endsWith("ServiceName") &&
          one.initializer !== undefined &&
          isStringLiteralLikeNode(one.initializer),
      ),
  );
  let found = named;
  const visit = (node: Node): void => {
    if (found) {
      return;
    }
    if (
      isPropertyAssignment(node) &&
      isIdentifier(node.name) &&
      node.name.text === "path" &&
      isStringLiteralLikeNode(node.initializer) &&
      SERVICE_PATH.test(node.initializer.text)
    ) {
      found = true;
      return;
    }
    node.forEachChild(visit);
  };
  file.forEachChild(visit);
  return found;
}

/** Whether one file imports a module by its specifier. */
function imports(file: SourceFile, module: string): boolean {
  return file.statements.some(
    (statement) =>
      isImportDeclaration(statement) &&
      isStringLiteralLikeNode(statement.moduleSpecifier) &&
      statement.moduleSpecifier.text === module,
  );
}

/** The option sets the rows of `references-ts.36` name, by row; every other row's is met by any output. */
const OPTION_SETS: Readonly<Record<string, (file: SourceFile) => boolean>> = {
  "ts-proto-2-output-schema": (file) => imports(file, "ts-proto-descriptors"),
  "ts-proto-2": writesServicePath,
  "ts-proto-2-types": (file) => !writesServicePath(file),
};

/** The first generator row one file matches, in `generators.json`'s order, as `bindings.3` reads it. */
export function generatorOf(file: SourceFile): GeneratorMatch | undefined {
  const lines = leadingComments(file.text).flat();
  for (const row of GENERATORS) {
    const header = new RegExp(row.header, "u");
    if (!lines.some((one) => header.test(one.text))) {
      continue;
    }
    const statements = STATEMENTS[row.plugin] ?? {};
    const [version] = statements.version === undefined ? [] : after(lines, statements.version);
    if (
      "versions" in row &&
      (version === undefined ||
        !satisfies(
          version.replace(/^v/u, ""),
          `>=${row.versions.min.replace(/^v/u, "")} <=${row.versions.max.replace(/^v/u, "")}`,
        ))
    ) {
      continue;
    }
    if (OPTION_SETS[row.id]?.(file) === false) {
      continue;
    }
    const schemaFiles =
      statements.schemaFiles === undefined
        ? []
        : [
            ...new Set(
              after(lines, statements.schemaFiles).filter((one) => one.endsWith(".proto")),
            ),
          ].sort(bytewise);
    return { row: row.id, ...(version === undefined ? {} : { version }), schemaFiles };
  }
  return undefined;
}

/**
 * Every own file of one project that is generated, by its path below the target root, with
 * what decided it: its leading comments' mark, else the row naming its directory as
 * generated, else its minified name or text; and the generator row it matches.
 */
export function generatedFilesOf(
  files: SourceFiles,
  byRow: ReadonlyMap<string, string>,
): ReadonlyMap<string, GeneratedFact> {
  const found = new Map<string, GeneratedFact>();
  for (const [path, file] of files.byPath) {
    const row = byRow.get(path);
    const minified = row === undefined ? minifiedBy(file.fileName, file.text) : undefined;
    const fact =
      generatedMark(file.text) ??
      (row === undefined
        ? minified === undefined
          ? undefined
          : { evidence: "minified" as const, line: 1, detail: minified }
        : { evidence: "convention" as const, line: 1, detail: row });
    if (fact === undefined) {
      continue;
    }
    const generator = generatorOf(file);
    found.set(path, generator === undefined ? fact : { ...fact, generator });
  }
  return found;
}

/** The detail a retention in a generated file names, from what decided the file. */
function retentionDetail(fact: GeneratedFact): string {
  switch (fact.evidence) {
    case "header":
      return "generated by the header line its leading comments hold";
    case "tag":
      return "generated by the @generated tag its leading comments hold";
    case "notice":
      return "generated by the notice its leading comments hold";
    case "convention":
      return `generated below a directory the convention row ${fact.detail} names`;
    case "minified":
      return "generated as a minified JavaScript file";
  }
}

/** The generated-file detector, recording each file's first line. */
export function generatedFile<Brand>(input: DetectorInput<Brand>): readonly Evidence[] {
  const generated = input.generated;
  if (generated === undefined || generated.size === 0) {
    return [];
  }
  return input.held.symbols.flatMap((symbol): Evidence[] => {
    const fact = generated.get(symbol.position.path);
    return symbol.kind === "file" || fact === undefined
      ? []
      : [
          {
            id: symbol.id,
            detail: retentionDetail(fact),
            site: { path: symbol.position.path, line: 1, column: 1 },
          },
        ];
  });
}
