/** A protoc-gen-es v2 file of package `c<at>`: its `GenFile` and two messages. */
function generated(at: number): string {
  const name = `c${String(at)}`;
  return [
    '// @generated by protoc-gen-es v2.16.0 with parameter "target=ts"',
    `// @generated from file ${name}/a.proto (package ${name}, syntax proto3)`,
    'import type { GenFile, GenMessage } from "@bufbuild/protobuf/codegenv2";',
    'import { fileDesc, messageDesc } from "@bufbuild/protobuf/codegenv2";',
    'import type { Message } from "@bufbuild/protobuf";',
    `export const file_${name}_a: GenFile = fileDesc("");`,
    `/**\n * @generated from message ${name}.Item\n */`,
    `export type Item = Message<"${name}.Item"> & {`,
    "  /**\n   * @generated from field: int32 number = 1;\n   */\n  number: number;",
    "};",
    `export const ItemSchema: GenMessage<Item> = messageDesc(file_${name}_a, 0);`,
    `/**\n * @generated from message ${name}.Envelope\n */`,
    `export type Envelope = Message<"${name}.Envelope"> & {`,
    "  /**\n   * @generated from field: string label = 1;\n   */\n  label: string;",
    "};",
    `export const EnvelopeSchema: GenMessage<Envelope> = messageDesc(file_${name}_a, 1);`,
    "",
  ].join("\n");
}

/**
 * How one file passes on the namespace object the module before it holds: a re-export, a
 * variable it exports holding the object or one of its members, an exported alias, or an
 * exported `namespace` declaration holding it in a variable, an alias or a nested namespace.
 */
const HOPS = [
  "star-as",
  "specifier",
  "default",
  "star",
  "named",
  "equals",
  "const",
  "const-specifier",
  "const-default",
  "const-member",
  "const-destructure",
  "alias",
  "namespace",
  "namespace-alias",
  "namespace-nested",
] as const;
type Hop = (typeof HOPS)[number];
/**
 * How the hand file binds what the last barrel exports: a namespace, named, `require` or alias
 * import, an awaited `import()` given to a `const`, or a `then` arrow callback's first parameter,
 * each a namespace binding (references-ts.4), or a `then` function callback's, a holder.
 */
const IMPORTS = ["namespace", "named", "require", "dynamic", "then", "alias"] as const;
/**
 * How a `then` callback is written: an arrow, which binds the value, or a function expression,
 * one with a `this` parameter before the binding, or one that passes its `arguments` object on,
 * each of which holds the value whole.
 */
const CALLBACKS = ["arrow", "function", "this", "arguments"] as const;
/**
 * How the hand file reads one property along the way: by name, by a literal or template index,
 * by a variable's destructuring, a parameter's default, a nested element's default, a nested
 * pattern or a defaulted element, by a rest element, by a computed index, by an index typed as the
 * property's literal name, or by a type parameter.
 */
const STEPS = [
  "member",
  "index",
  "template",
  "destructure",
  "default",
  "element",
  "nested",
  "defaulted",
  "rest",
  "computed",
  "key",
  "param",
] as const;
type Step = (typeof STEPS)[number];
/** The steps that read one property alone (references-ts.4); every other reads whole (.5). */
const BY_NAME: ReadonlySet<Step> = new Set(["member", "index", "template", "destructure"]);
/** The steps that read by an object pattern, whose binding of a namespace value holds it whole. */
const PATTERNS: ReadonlySet<Step> = new Set(["destructure"]);
/** The hops whose file gives the namespace value to a binding, which holds it whole (.5). */
const HOLDING: ReadonlySet<Hop> = new Set([
  "const",
  "const-specifier",
  "const-default",
  "const-member",
  "const-destructure",
  "namespace",
  "namespace-nested",
]);

