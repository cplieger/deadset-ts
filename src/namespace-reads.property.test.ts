interface Drawn {
  readonly hops: readonly Hop[];
  /** Per hop, whether its file shadows the name it imports with a whole use of its own. */
  readonly shadows: readonly boolean[];
  /** Whether the reader is a file of its own that the entry file imports, or the entry file. */
  readonly apart: boolean;
  /** Whether the reader shadows its binding with a whole use of its own. */
  readonly shadowed: boolean;
  /** Whether the entry file also re-exports the last module, whose callers then use it whole. */
  readonly rooted: boolean;
  readonly imported: (typeof IMPORTS)[number];
  readonly callback: (typeof CALLBACKS)[number];
  readonly steps: readonly Step[];
  /** Whether the namespace object is held in a variable before it is read. */
  readonly held: boolean;
  /** Whether the hand file uses the namespace object whole, rather than reading one export. */
  readonly whole: boolean;
  /** Whether the reader holds its binding in a `namespace` of its own file before reading it. */
  readonly nested: boolean;
  /** Whether a file nothing imports uses the last module whole. */
  readonly dead: boolean;
  /** Whether the reader writes a statement label spelled as its binding, which is no use (.3). */
  readonly labelled: boolean;
  /** Which hand-written namespace value the reader reads whole, how, and through which import. */
  readonly value: (typeof VALUES)[number];
  readonly valueRead: (typeof VALUE_READS)[number];
  readonly valueImport: (typeof VALUE_IMPORTS)[number];
  /** Whether the checker fails at that read's name, which leaves it a whole use of what it may be. */
  readonly valuePanics: boolean;
}

