/** One composed case: the files it writes and what `main.ts` writes for it. */
interface Composed {
  readonly files: Readonly<Record<string, string>>;
  /**
   * Whether a read of the chain is whole (references-ts.5): a binding along it holds a namespace
   * value, or a step reads it by any form but a name, a literal index or a destructuring.
   */
  readonly escapes: boolean;
  readonly reader: string;
  readonly label: string;
  /**
   * Where the checker fails, if it is drawn to: the file holding the reader, and the text that
   * ends just before the first name of the reader's last read, after the reader's head.
   */
  readonly panic?: Panic;
  /** Where the checker fails at the whole read of the hand-written value, if it is drawn to. */
  readonly valuePanic?: Panic;
  /** The declarations the whole read of the hand-written value reaches, by name. */
  readonly reached: readonly string[];
}

/** A place the checker fails at: the text that ends just before the name, after `head` in `path`. */
interface Panic {
  readonly path: string;
  readonly head: string;
  readonly before: string;
}

/** A block shadowing `name` with a whole use of a value no module holds. */
const shadowing = (name: string): string =>
  `{\n  const ${name} = { ItemSchema: 1 };\n  console.log(${name});\n}\n`;

/**
 * The files one drawn case writes: the generated file, one file per hop (depth 1 to 3), each
 * passing on the namespace value the module before it holds under the path of export names it
 * is reached by, the hand-written values, and the reader, in the entry file or its own. A hop that
 * cannot pass on that path is drawn as `export * as`. `export =` only ends a chain, whose importer
 * is then a `require`, and a CommonJS file's dynamic import gives a `default` of its own, so one
 * along a path through `default` is drawn as a namespace import.
 */
function composed(one: Drawn, at: number, commonjs: boolean, panics = false): Composed {
  const dir = `src/c${String(at)}`;
  const files: Record<string, string> = { [`${dir}/gen/a_pb.ts`]: generated(at) };
  let from = "./gen/a_pb.js";
  let path: readonly string[] = [];
  let equals = false;
  const hops: string[] = [];
  let holds = false;
  one.hops.forEach((drawnHop, level) => {
    const last = level === one.hops.length - 1;
    const valid: Record<Hop, boolean> = {
      "star-as": true,
      specifier: true,
      default: true,
      star: path[0] !== "default",
      named: path.length > 0,
      equals: last && commonjs,
      const: true,
      "const-specifier": true,
      "const-default": true,
      "const-member": path.length > 0,
      "const-destructure": path.length > 0,
      alias: true,
      namespace: true,
      "namespace-alias": true,
      "namespace-nested": true,
    };
    const hop: Hop = valid[drawnHop] ? drawnHop : "star-as";
    const name = `n${String(level)}`;
    const [first, ...rest] = path;
    const m = `import * as m from "${from}";\n`;
    const text: Record<Hop, () => string> = {
      "star-as": () => `export * as ${name} from "${from}";\n`,
      specifier: () => `${m}export { m as ${name} };\n`,
      default: () => `${m}export default m;\n`,
      star: () => `export * from "${from}";\n`,
      named: () => `export { ${first ?? ""} as ${name} } from "${from}";\n`,
      equals: () => `import m = require("${from}");\nexport = m;\n`,
      const: () => `${m}export const ${name} = m;\n`,
      "const-specifier": () => `${m}const held = m;\nexport { held as ${name} };\n`,
      "const-default": () => `${m}const held = m;\nexport default held;\n`,
      "const-member": () => `${m}export const ${name} = m.${first ?? ""};\n`,
      "const-destructure": () => `${m}export const { ${first ?? ""}: ${name} } = m;\n`,
      alias: () => `${m}export import ${name} = m;\n`,
      namespace: () => `${m}export namespace ${name} {\n  export const inner = m;\n}\n`,
      "namespace-alias": () => `${m}export namespace ${name} {\n  export import inner = m;\n}\n`,
      "namespace-nested": () =>
        `${m}export namespace ${name} {\n  export namespace inner {\n    export const held = m;\n  }\n}\n`,
    };
    const shadow = one.shadows[level] === true ? shadowing("m") : "";
    files[`${dir}/b${String(level)}.ts`] = `${text[hop]()}${shadow}`;
    hops.push(`${hop}${shadow === "" ? "" : "+shadow"}`);
    holds ||= HOLDING.has(hop);
    const passed = hop === "named" || hop === "const-member" || hop === "const-destructure";
    path =
      hop === "default" || hop === "const-default"
        ? ["default", ...path]
        : passed
          ? [name, ...rest]
          : hop === "namespace" || hop === "namespace-alias"
            ? [name, "inner", ...path]
            : hop === "namespace-nested"
              ? [name, "inner", "held", ...path]
              : hop === "star" || hop === "equals"
                ? path
                : [name, ...path];
    equals = hop === "equals";
    from = `./b${String(level)}.js`;
  });
  const module = one.apart ? from : `./c${String(at)}/${from.slice(2)}`;
  const imported = equals
    ? "require"
    : (one.imported === "require" && !commonjs) ||
        ((one.imported === "dynamic" || one.imported === "then") &&
          commonjs &&
          path[0] === "default")
      ? "namespace"
      : one.imported;
  const binding = `b${String(at)}`;
  const lines: string[] = [];
  let head = `import * as ${binding} from "${module}";`;
  let remaining = path;
  if (imported === "named" && path.length > 0) {
    const [first, ...rest] = path;
    head =
      first === "default"
        ? `import ${binding} from "${module}";`
        : `import { ${first ?? ""} as ${binding} } from "${module}";`;
    remaining = rest;
  } else if (imported === "require") {
    head = `import ${binding} = require("${module}");`;
  } else if (imported === "alias") {
    head = `import * as t${String(at)} from "${module}";\nimport ${binding} = t${String(at)};`;
  } else if (imported === "dynamic") {
    head = "";
    lines.push(`  const ${binding} = await import("${module}");`);
  } else if (imported === "then") {
    head = "";
    const opened =
      one.callback === "arrow"
        ? `(${binding}) =>`
        : one.callback === "this"
          ? `function (this: void, ${binding})`
          : `function (${binding})`;
    lines.push(`  await import("${module}").then(${opened} {`);
    if (one.callback === "arguments") {
      lines.push("  console.log(arguments[0]);");
    }
  }
  let expression = binding;
  let local = 0;
  // A `namespace` is declared at a file's top level, where a dynamic import's binding is not.
  const nested = one.nested && imported !== "dynamic" && imported !== "then";
  const namespace = nested
    ? `namespace H${String(at)} {\n  export const held = ${binding};\n}`
    : "";
  if (nested) {
    expression = `H${String(at)}.held`;
  }
  // A holder given a namespace value holds it whole, as does every read but the three forms by
  // name; an exported `const` in the reader's `namespace` is one, a local `const` binds the value.
  // A CommonJS file's `import()` binds it too, whatever type its interop object has (.4).
  let escapes = holds || nested || (imported === "then" && one.callback !== "arrow");
  const read = (property: string, how: Step, last: boolean): void => {
    escapes ||= !BY_NAME.has(how) || (PATTERNS.has(how) && !last);
    local += 1;
    const at = String(local);
    if (how === "member") {
      expression = `${expression}.${property}`;
    } else if (how === "index") {
      expression = `${expression}["${property}"]`;
    } else if (how === "template") {
      expression = `${expression}[\`${property}\`]`;
    } else if (how === "computed") {
      expression = `${expression}[("${property}")]`;
    } else if (how === "key") {
      lines.push(`  const k${at} = "${property}";`);
      expression = `${expression}[k${at}]`;
    } else if (how === "param") {
      expression = `(<K${at} extends "${property}">(k: K${at}) => ${expression}[k])("${property}")`;
    } else if (how === "default") {
      // The last read's pattern is typed apart from its default, so only the value names the member.
      const typed = last ? ": Record<string, unknown>" : "";
      lines.push(`  const v${at} = (({ ${property}: p }${typed} = ${expression}) => p)();`);
      expression = `v${at}`;
    } else if (how === "element") {
      lines.push(
        `  const { box: { ${property}: v${at} } = ${expression} } = {} as { box?: undefined };`,
      );
      expression = `v${at}`;
    } else if (how === "nested") {
      lines.push(`  const { ${property}: { ...v${at} } } = ${expression};`);
      expression = `v${at}`;
    } else if (how === "defaulted") {
      lines.push(`  const { ${property}: v${at} = ${expression}.${property} } = ${expression};`);
      expression = `v${at}`;
    } else if (how === "rest") {
      lines.push(`  const { ...v${at} } = ${expression};`);
      expression = `v${at}.${property}`;
    } else {
      lines.push(`  const { ${property}: v${at} } = ${expression};`);
      expression = `v${at}`;
    }
  };
  remaining.forEach((property, step) => {
    read(property, one.steps[step] ?? "member", false);
  });
  if (one.shadowed) {
    lines.push(
      ...shadowing(binding)
        .trimEnd()
        .split("\n")
        .map((line) => `  ${line}`),
    );
  }
  if (one.held) {
    local += 1;
    lines.push(`  const v${String(local)} = ${expression};`);
    expression = `v${String(local)}`;
  }
  if (one.labelled) {
    lines.push(`  ${binding}: for (;;) {`, `    break ${binding};`, "  }");
  }
  const last = one.whole ? "  console.log(Object.keys(" : "  console.log(";
  if (one.whole) {
    lines.push(`  console.log(Object.keys(${expression}));`);
  } else {
    read("ItemSchema", one.steps[remaining.length] ?? "member", true);
    lines.push(`  console.log(${expression});`);
  }
  if (imported === "then") {
    lines.push("  });");
  }
  const value = valueRead(one, at, one.apart ? "./" : `./c${String(at)}/`);
  files[`${dir}/values.ts`] = VALUE_TEXT;
  if (value.barrel !== undefined) {
    files[`${dir}/vbarrel.ts`] = value.barrel;
  }
  if (value.statement !== "") {
    lines.push(`  ${value.statement}`);
  }
  const reader = `export async function read${String(at)}(): Promise<void> {`;
  const body = [head, value.head, namespace, reader, ...lines, "}"].join("\n");
  const entry = `./c${String(at)}/${from.slice(2)}`;
  const root = [
    ...(!one.rooted
      ? []
      : equals
        ? [`import r${String(at)} = require("${entry}");`, `export { r${String(at)} };`]
        : [`export * as r${String(at)} from "${entry}";`]),
    ...(value.root === undefined ? [] : [value.root]),
  ];
  if (one.apart) {
    files[`${dir}/reader.ts`] = `${body}\n`;
  }
  if (one.dead) {
    files[`${dir}/dead.ts`] = [
      equals ? `import d = require("${from}");` : `import * as d from "${from}";`,
      "export function unused(): void {",
      "  console.log(d);",
      "}",
      "",
    ].join("\n");
  }
  return {
    files,
    escapes,
    reader: [
      ...(one.apart
        ? [`import { read${String(at)} } from "./c${String(at)}/reader.js";`]
        : [body.replace(reader, reader.slice("export ".length))]),
      ...root,
      `void read${String(at)}();`,
    ].join("\n"),
    reached: VALUE_MEMBERS[one.value],
    ...(one.valuePanics && value.statement !== ""
      ? {
          valuePanic: {
            path: one.apart ? `${dir}/reader.ts` : "src/main.ts",
            head: reader.slice("export ".length),
            before: value.before,
          },
        }
      : {}),
    label: `${one.value} ${value.statement}${value.root ?? ""}${one.valuePanics ? " (fails)" : ""} | ${hops.join(" > ")} | ${imported}${imported === "then" ? ` ${one.callback}` : ""} | ${one.steps.slice(0, remaining.length + 1).join(",")}${one.held ? " | held" : ""}${one.whole ? " | whole" : ""}${one.apart ? " | apart" : ""}${one.shadowed ? " | shadowed" : ""}${one.rooted ? " | rooted" : ""}${nested ? " | nested" : ""}${one.dead ? " | dead" : ""}${one.labelled ? " | labelled" : ""}${panics ? " | panics" : ""}`,
    ...(panics
      ? {
          panic: {
            path: one.apart ? `${dir}/reader.ts` : "src/main.ts",
            head: reader.slice("export ".length),
            before: `\n${last}`,
          },
        }
      : {}),
  };
}

/**
 * How one case's reader reads its hand-written value whole: the import it writes, from the
 * reader's directory `at`, the barrel file that import may read through, the statement, the text
 * ending just before the last name of the value the statement reads, and the entry file's
 * re-export of the value where it reads none.
 */
function valueRead(
  one: Drawn,
  at: number,
  from: string,
): {
  readonly head: string;
  readonly barrel?: string;
  readonly statement: string;
  readonly before: string;
  readonly root?: string;
} {
  const n = String(at);
  const name = VALUE_NAMES[one.value];
  const imports: Record<
    (typeof VALUE_IMPORTS)[number],
    { head: string; qualifier: string; local: string; barrel?: string }
  > = {
    named: {
      head: `import { ${name} as h${name}${n} } from "${from}values.js";`,
      qualifier: "",
      local: `h${name}${n}`,
    },
    member: {
      head: `import * as hv${n} from "${from}values.js";`,
      qualifier: `hv${n}.`,
      local: name,
    },
    barrel: {
      head: `import { ${name} as h${name}${n} } from "${from}vbarrel.js";`,
      qualifier: "",
      local: `h${name}${n}`,
      barrel: `export { ${name} } from "./values.js";\n`,
    },
    renamed: {
      head: `import { R${name} as h${name}${n} } from "${from}vbarrel.js";`,
      qualifier: "",
      local: `h${name}${n}`,
      barrel: `export { ${name} as R${name} } from "./values.js";\n`,
    },
    default: {
      head: `import h${name}${n} from "${from}vbarrel.js";`,
      qualifier: "",
      local: `h${name}${n}`,
      barrel: `import { ${name} } from "./values.js";\nexport default ${name};\n`,
    },
    "star-as": {
      head: `import { vals as hvals${n} } from "${from}vbarrel.js";`,
      qualifier: `hvals${n}.`,
      local: name,
      barrel: 'export * as vals from "./values.js";\n',
    },
  };
  const { head, qualifier, local, barrel } = imports[one.valueImport];
  const typed = one.value === "class" || one.value === "enum";
  const how =
    (one.valueRead === "new" || one.valueRead === "extends") && one.value !== "class"
      ? "log"
      : one.valueRead === "call" && one.value !== "function"
        ? "log"
        : one.valueRead === "annotated" && !typed
          ? "typeof"
          : one.valueRead;
  if (how === "root") {
    return {
      head: "",
      statement: "",
      before: "",
      root: `export { ${name} as rv${n} } from "./c${n}/values.js";`,
    };
  }
  const prefix: Record<(typeof VALUE_READS)[number], readonly [string, string]> = {
    log: [`console.log("v${n}", `, ")"],
    holder: [`const hw${n} = `, `;\n  console.log(hw${n})`],
    spread: [`console.log("v${n}", { ...`, " })"],
    keys: [`console.log("v${n}", Object.keys(`, "))"],
    new: [`console.log("v${n}", new `, "())"],
    extends: [`console.log("v${n}", class extends `, " {})"],
    call: [`console.log("v${n}", `, "())"],
    typeof: [`console.log("v${n}", undefined as typeof `, " | undefined)"],
    indexed: [
      `console.log("v${n}", undefined as (typeof `,
      `)["${VALUE_MEMBER[one.value]}"] | undefined)`,
    ],
    annotated: [`console.log("v${n}", undefined as `, " | undefined)"],
    root: ["", ""],
  };
  const [before, after] = prefix[how];
  return {
    head,
    ...(barrel === undefined ? {} : { barrel }),
    statement: `${before}${qualifier}${local}${after};`,
    before: `\n  ${before}${qualifier}`,
  };
}

/** What one analysis of the written cases gives each case. */
interface Analyzed {
  /** The consumer facts: Item and Envelope. */
  readonly states: Readonly<Record<string, string>>;
  /**
   * Each read hand code outside the unreached file makes of the case's generated file or of
   * a declaration of its chain that carries no `namespace` mark: a read no rule judged.
   */
  readonly unjudged: readonly string[];
  /** The findings of the report naming a declaration the whole read of the case's value reaches. */
  readonly deadReached: readonly string[];
}

/** What one analysis of the written cases gives each case, its facts and its references. */
function statesOf(cases: readonly Composed[], commonjs: boolean): readonly Analyzed[] {
  const files: Record<string, string> = {
    "deadset.json": JSON.stringify({
      target: { kind: "application" },
      analysis: { min_confidence: "possible" },
      ts: { entry_files: ["src/main.ts"] },
    }),
    "package.json": `{ "name": "@example/app", "private": true${commonjs ? "" : ', "type": "module"'} }\n`,
    "tsconfig.json": TSCONFIG,
    ...RUNTIME,
    ...Object.assign({}, ...cases.map((one) => one.files)),
    "src/main.ts": `${cases.map((one) => one.reader).join("\n")}\n`,
  };
  // Each drawn panic fails the question for the name at its place, in both analyses.
  const failing = cases.flatMap(({ panic, valuePanic }) =>
    [panic, valuePanic].flatMap((one) => {
      const text = one === undefined ? undefined : files[one.path];
      if (one === undefined || text === undefined) {
        return [];
      }
      const at = text.indexOf(one.before, text.indexOf(one.head)) + one.before.length;
      return [`/${one.path}:${String(at)}`];
    }),
  );
  const panicsOn = (accessor: string, locations: readonly string[]): boolean =>
    accessor === "getSymbolAtLocation" &&
    locations.some((one) => failing.some((place) => one.endsWith(place)));
  const root = writeProject(files);
  const dir = mkdtempSync(join(tmpdir(), "deadset-ts-namespace-reads-"));
  try {
    const err = new MemoryWriter();
    run(
      [
        "analyze",
        `--target=${root}`,
        `--report=${join(dir, "report.json")}`,
        `--facts=${join(dir, "facts.json")}`,
      ],
      new MemoryWriter(),
      err,
      { ...nodeHost(), workingDirectory: () => root, analyzerVersion: () => "0.0.0" },
      (options: EngineOptions): Engine => {
        const opened = openEngine(options);
        return {
          ...opened,
          ask: (accessor, locations, question) => {
            if (panicsOn(accessor, locations())) {
              throw new Error(`panic: ${accessor}`);
            }
            return opened.ask(accessor, locations, question);
          },
        };
      },
    );
    expect(
      err.text
        .split("\n")
        .filter((line) => line !== "")
        .filter(
          (line) =>
            failing.length === 0 ||
            !/^deadset-ts: the checker answered \d+ questions? with a failure /u.test(line),
        ),
    ).toEqual([]);
    const report = JSON.parse(readFileSync(join(dir, "report.json"), "utf8")) as {
      readonly findings: readonly {
        readonly code: string;
        readonly position: { readonly path: string };
        readonly symbol: { readonly name: string };
        readonly liveness_relation?: string;
      }[];
    };
    const document = JSON.parse(readFileSync(join(dir, "facts.json"), "utf8")) as {
      readonly bindings: readonly {
        readonly role: string;
        readonly symbol: string;
        readonly state?: string;
        readonly cap?: string;
      }[];
    };
    const analyzed = analyzeRoot(root, { references: { testFiles: [] }, panicsOn });
    const symbols = analyzed.inventories[0]?.symbols ?? [];
    const paths = new Map(symbols.map((one) => [one.id, one.position.path]));
    const files = new Set(symbols.filter((one) => one.kind === "file").map((one) => one.id));
    const references = analyzed.references[0]?.references ?? [];
    return cases.map((_one, at) => {
      const dir = `src/c${String(at)}/`;
      // The generated file itself, and any declaration of a hop's file.
      const chained = (id: string, path: string): boolean =>
        (files.has(id) && path === `${dir}gen/a_pb.ts`) ||
        (path.startsWith(dir) && /^b\d\.ts$/u.test(path.slice(dir.length)));
      const unjudged = references.flatMap((one) => {
        const from = paths.get(one.from) ?? "";
        const to = paths.get(one.to) ?? "";
        return one.use === "read" &&
          one.namespace !== true &&
          !from.startsWith(`${dir}gen/`) &&
          from !== `${dir}dead.ts` &&
          chained(one.to, to)
          ? [`${from} -> ${to} at ${String(one.position.line)}:${String(one.position.column)}`]
          : [];
      });
      const states: Record<string, string> = {};
      for (const binding of document.bindings) {
        const [file, name] = binding.symbol.split("#");
        if (binding.role === "consumer" && file?.endsWith(`/c${String(at)}/gen/a_pb.ts`) === true) {
          states[name ?? ""] = [binding.state, binding.cap]
            .filter((part) => part !== undefined)
            .join(" ");
        }
      }
      const reached = new Set(cases[at]?.reached ?? []);
      const deadReached = report.findings.flatMap((finding) =>
        /^DS100[135]$/u.test(finding.code) &&
        finding.position.path === `${dir}values.ts` &&
        reached.has(finding.symbol.name)
          ? [`${finding.code} ${finding.symbol.name} ${finding.liveness_relation ?? "-"}`]
          : [],
      );
      return {
        states: { Item: states["Item"] ?? "", Envelope: states["Envelope"] ?? "" },
        unjudged,
        deadReached,
      };
    });
  } finally {
    rmSync(root, { recursive: true, force: true });
    rmSync(dir, { recursive: true, force: true });
  }
}

/** Whether one consumer's state and cap keep at least what another's do. */
function atLeast(got: string, wanted: string): boolean {
  const [state, ...caps] = wanted.split(" ");
  const [gotState, ...gotCaps] = got.split(" ");
  return (state !== "live" || gotState === "live") && caps.every((cap) => gotCaps.includes(cap));
}

describe("a namespace object read through a chain of re-exports", () => {
  // Property: nothing a drawn read can reach is reported dead, under either relation, and a read
  // by name, a literal index or an object pattern of names reads one export alone (references-ts.3
  // to .5); a holder given the value, a whole use and a root's re-export read every export, live
  // and exposed (.34), and a whole use nothing reaches exposes without keeping (bindings.11). A
  // whole read of a hand-written nested, merged class, enum or function namespace reads every
  // member, answered or not, so no finding names one; a failed question drops no read.
  it("leaves live every export a drawn read can reach, and only the export a read by name names", () => {
    fc.assert(
      fc.property(
        fc.array(drawn, { minLength: 1, maxLength: 6 }),
        fc.boolean(),
        fc.option(fc.nat({ max: 5 }), { freq: 2 }),
        (draws, commonjs, panicking) => {
          const panicAt = panicking === null ? undefined : panicking % draws.length;
          const cases = draws.map((one, at) => composed(one, at, commonjs, at === panicAt));
          const states = statesOf(cases, commonjs);
          const failed = panicAt !== undefined || cases.some((one) => one.valuePanic !== undefined);
          cases.forEach((one, at) => {
            const draw = draws[at];
            const whole = draw?.whole === true || draw?.rooted === true || one.escapes;
            const label = `${commonjs ? "CommonJS" : "ESM"} ${one.label}\n${one.reader}`;
            const capped = draw?.dead === true;
            const everything = {
              Item: "live descriptor-exposure",
              Envelope: "live descriptor-exposure",
            };
            const expected = whole
              ? everything
              : capped
                ? { Item: "live descriptor-exposure", Envelope: "unreferenced descriptor-exposure" }
                : { Item: "live", Envelope: "unreferenced" };
            const got = states[at];
            expect(
              got?.deadReached,
              `${label}\nreported dead though a whole read reaches it`,
            ).toEqual([]);
            // A name the checker leaves unanswered may stand for any file (program.33), so a
            // drawn panic, at a reader's name or at a value's, may leave any case of its analysis
            // more live, and none less.
            if (!failed) {
              for (const name of ["Item", "Envelope"] as const) {
                expect(
                  atLeast(got?.states[name] ?? "", expected[name]),
                  `${label}\n${name} is less live than a drawn read can reach`,
                ).toBe(true);
              }
              expect(got?.states, label).toEqual(expected);
              if (draw?.whole !== true && !one.escapes) {
                expect(got?.unjudged, label).toEqual([]);
              }
            } else if (at === panicAt && got !== undefined && got.unjudged.length > 0) {
              expect(got.states, `${label}\nunjudged: ${got.unjudged.join(", ")}`).toEqual(
                everything,
              );
            } else {
              for (const name of ["Item", "Envelope"] as const) {
                expect(atLeast(got?.states[name] ?? "", expected[name]), `${label} ${name}`).toBe(
                  true,
                );
              }
            }
          });
        },
      ),
      {
        numRuns: RUNS,
        // A function callback read by name, which holds the value, beside an arrow, which binds it;
        // a CommonJS file's awaited `import()` read by name.
        examples: [
          [[{ ...PLAIN, callback: "function" }, PLAIN], false, null],
          [[{ ...PLAIN, imported: "dynamic" }], true, null],
        ],
        plugins: [fc.interruptAfterTimeLimit(240_000, { failOnInterrupt: true })],
      },
    );
  }, 300_000);
});
