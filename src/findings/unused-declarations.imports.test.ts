import { rmSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { emitterInputOf, findingsOf } from "../../__test-helpers__/emitter-input.ts";
import { writeProject } from "../../__test-helpers__/projects.ts";
import { treeFindings } from "../../__test-helpers__/tree-findings.ts";
import { resolve } from "../resolve.ts";

const LOAD_TIMEOUT = 60_000;

const LIB = [
  "export const a = 1;",
  "export const b = 2;",
  "export interface Shape { readonly n: number }",
  "export default function make(): number { return 3; }",
  "",
].join("\n");

/** The DS1002 findings of an application tree, as `<name> <path>:<line>`. */
function unusedImports(files: Readonly<Record<string, string>>): readonly string[] {
  return treeFindings(files)
    .filter((one) => one.startsWith("DS1002 "))
    .map((one) => one.slice("DS1002 ".length));
}

/** Each finding about an import binding of a tree analysed under `document`, as `<code> <ref>`. */
function importFindings(files: Readonly<Record<string, string>>, document: object): string[] {
  const root = writeProject(files);
  try {
    const { config } = resolve({
      repository: JSON.stringify(document),
      repositoryLabel: "deadset.json",
    });
    return findingsOf(emitterInputOf(root, config))
      .filter((one) => one.symbol.kind === "import")
      .map((one) => `${one.code} ${one.symbol.ref} ${one.fixability} ${one.confidence}`);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
}

describe("an import binding", () => {
  it("is reported where its file reads it nowhere, a default, named and namespace binding each", () => {
    expect(
      unusedImports({
        "lib.ts": LIB,
        "main.ts": [
          'import make, { a, b as renamed, type Shape } from "./lib.js";',
          'import * as whole from "./lib.js";',
          "console.log(a);",
          "",
        ].join("\n"),
      }),
    ).toEqual(["make", "renamed", "Shape", "whole"]);
  });

  it("is read by a type position, a local export, a shorthand property and a doc comment", () => {
    expect(
      unusedImports({
        "lib.ts": LIB,
        "main.ts": [
          'import make, { a, b, type Shape } from "./lib.js";',
          'import * as whole from "./lib.js";',
          "/** Built by {@link make}. */",
          "export const shaped: Shape = { n: a };",
          "export { b };",
          "console.log({ whole }, shaped);",
          "",
        ].join("\n"),
      }),
    ).toEqual([]);
  });

  it("is reported where a doc comment names it only in prose", () => {
    expect(
      unusedImports({
        "lib.ts": LIB,
        "main.ts": [
          'import make, { a } from "./lib.js";',
          "/** Unlike make, this reads a. */",
          "export const shaped = 1;",
          "console.log(a);",
          "",
        ].join("\n"),
      }),
    ).toEqual(["make"]);
  });

  it("is reported where only another binding of its name is read", () => {
    expect(
      unusedImports({
        "lib.ts": LIB,
        "main.ts": [
          'import { a } from "./lib.js";',
          "function shadow(a: number): number { return a; }",
          "console.log(shadow(1));",
          "",
        ].join("\n"),
      }),
    ).toEqual(["a"]);
  });

  it("is reported in a file nothing imports, as the file's declarations are", () => {
    expect(
      treeFindings({
        "lib.ts": LIB,
        "main.ts": "console.log(1);\n",
        "orphan.ts": 'import { a } from "./lib.js";\nexport const unused = 1;\n',
      }).filter((one) => one.startsWith("DS1002")),
    ).toEqual(["DS1002 a"]);
  });

  it("is not reported in a generated file, whose generator owns its imports", () => {
    expect(
      unusedImports({
        "lib.ts": LIB,
        "main.ts": 'import "./wire.js";\n',
        "wire.ts":
          '// Code generated by wiregen. DO NOT EDIT.\nimport { a } from "./lib.js";\nexport const wire = 1;\n',
      }),
    ).toEqual([]);
  });

  it(
    "is reported under its own reference, deletable, for an import equals declaration too",
    () => {
      expect(
        importFindings(
          {
            "package.json":
              '{ "name": "@example/cjs", "private": true, "main": "./src/main.ts" }\n',
            "tsconfig.json": JSON.stringify({
              compilerOptions: { strict: true, module: "commonjs", noEmit: true, types: [] },
              include: ["src/**/*.ts"],
            }),
            "src/lib.ts": "export const a = 1;\n",
            "src/main.ts":
              'import lib = require("./lib");\nimport { a } from "./lib";\nexport const b = 1;\n',
          },
          { target: { kind: "application" } },
        ),
      ).toEqual([
        "DS1002 ts://@example/cjs/src/main.ts#lib:import deletable certain",
        "DS1002 ts://@example/cjs/src/main.ts#a:import deletable certain",
      ]);
    },
    LOAD_TIMEOUT,
  );

  it(
    "is read by the JSX a file writes where the compiler calls the factory it names",
    () => {
      const files = (jsx: string): Record<string, string> => ({
        "package.json":
          '{ "name": "@example/jsx", "private": true, "type": "module", "main": "./main.tsx" }\n',
        "tsconfig.json": JSON.stringify({
          compilerOptions: { strict: true, jsx, module: "nodenext", noEmit: true, types: [] },
          include: ["*.tsx", "*.ts"],
        }),
        "react.ts": [
          "export function createElement(..._args: unknown[]): unknown { return null; }",
          "declare global { namespace JSX { interface IntrinsicElements { p: object } } }",
          "",
        ].join("\n"),
        "main.tsx": 'import * as React from "./react.js";\nconsole.log(<p />);\n',
      });
      const document = { target: { kind: "application" } };
      expect(importFindings(files("react"), document)).toEqual([]);
      expect(importFindings(files("react-jsx"), document)).toEqual([
        "DS1002 ts://@example/jsx/main.tsx#React:import deletable certain",
      ]);
    },
    LOAD_TIMEOUT,
  );
});
