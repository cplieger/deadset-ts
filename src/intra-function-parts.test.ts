import { describe, expect, it } from "vitest";
import { LOAD_TIMEOUT, partsOf, tsconfigWith } from "../__test-helpers__/intra-function-parts.ts";

describe("an unreachable statement", () => {
  it(
    "follows a block that leaves, and an if statement both of whose branches leave",
    () => {
      expect(
        partsOf([
          "function inBlock(): number {",
          "  {",
          '    console.log("first");',
          "    return 1;",
          "  }",
          '  console.log("after the block");',
          "}",
          "",
          "function bothBranches(flag: boolean): number {",
          "  if (flag) {",
          "    return 1;",
          "  } else {",
          "    return 2;",
          "  }",
          '  console.log("after the if");',
          "}",
          "",
          "function thenOnly(flag: boolean): number {",
          "  if (flag) {",
          "    return 1;",
          "  }",
          '  console.log("reached");',
          "  return 2;",
          "}",
          "",
          "console.log(inBlock(), bothBranches(true), thenOnly(true));",
        ]),
      ).toEqual(["DS1405 statement src/main.ts:6", "DS1405 statement src/main.ts:15"]);
    },
    LOAD_TIMEOUT,
  );

  it(
    "is reported once per statement list, at the first, and never again inside the code it starts",
    () => {
      expect(
        partsOf([
          "function twice(): number {",
          "  return 1;",
          '  console.log("first");',
          '  console.log("second");',
          "}",
          "",
          "function nested(flag: boolean): number {",
          "  return 1;",
          "  if (flag) {",
          "    return 2;",
          '    console.log("deeper");',
          "  }",
          "}",
          "",
          "console.log(twice(), nested(true));",
        ]),
      ).toEqual(["DS1405 statement src/main.ts:3", "DS1405 statement src/main.ts:9"]);
    },
    LOAD_TIMEOUT,
  );

  it(
    "is no var that initializes nothing, and is a var that initializes any name or a let",
    () => {
      expect(
        partsOf([
          "function hoistedVar(): number {",
          "  return 1;",
          "  var spare;",
          "}",
          "",
          "function initializedVar(): number {",
          "  return 1;",
          "  var set = 2;",
          "}",
          "",
          "function partlyInitialized(): number {",
          "  return 1;",
          "  var first,",
          "    second = 2;",
          "}",
          "",
          "function blockScoped(): number {",
          "  return 1;",
          "  let later;",
          "}",
          "",
          "console.log(hoistedVar(), initializedVar(), partlyInitialized(), blockScoped());",
        ]),
      ).toEqual([
        "DS1404 spare src/main.ts:3",
        "DS1404 set src/main.ts:8",
        "DS1405 statement src/main.ts:8",
        "DS1404 first src/main.ts:13",
        "DS1405 statement src/main.ts:13",
        "DS1404 second src/main.ts:14",
        "DS1404 later src/main.ts:19",
        "DS1405 statement src/main.ts:19",
      ]);
    },
    LOAD_TIMEOUT,
  );

  it(
    "still makes the calls written in it, which leave the callee's signature free",
    () => {
      expect(
        partsOf([
          "function helper(value: number, unused: number): number {",
          "  return value;",
          "}",
          "",
          "function early(): number {",
          "  return 1;",
          "  helper(1, 2);",
          "}",
          "",
          "console.log(early());",
        ]),
      ).toEqual([
        "DS1401 unused src/main.ts:1",
        "DS1403 result src/main.ts:1",
        "DS1405 statement src/main.ts:7",
      ]);
    },
    LOAD_TIMEOUT,
  );

  it(
    "holds no dead store, duplicate case or unread catch binding of its own, and is the first statement the compiler marks inside a block it enters",
    () => {
      expect(
        partsOf([
          "function silenced(kind: string): number {",
          "  return 1;",
          "  {",
          "    let value = 1;",
          "    value = 2;",
          "    console.log(value);",
          "    switch (kind) {",
          '      case "a":',
          "        break;",
          '      case "a":',
          "        break;",
          "    }",
          "    try {",
          "      console.log(kind);",
          "    } catch (error) {",
          '      console.log("failed");',
          "    }",
          "  }",
          "}",
          "",
          'console.log(silenced("a"));',
        ]),
      ).toEqual(["DS1405 statement src/main.ts:4"]);
    },
    LOAD_TIMEOUT,
  );
});

