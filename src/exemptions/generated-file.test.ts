import { rmSync } from "node:fs";
import { afterAll, describe, expect, it } from "vitest";
import { emitterInputOf, findingsOf } from "../../__test-helpers__/emitter-input.ts";
import { writeProject } from "../../__test-helpers__/projects.ts";
import { generatedMark, generatorOf } from "./generated-file.ts";
import { openEngine } from "../session.ts";
import { resolve } from "../resolve.ts";

/** A project whose installed framework names `.nuxt` as the directory it generates. */
const PROJECT: Readonly<Record<string, string>> = {
  "package.json":
    '{ "name": "@example/app", "type": "module", "devDependencies": { "nuxt": "4.999.0" } }\n',
  "node_modules/nuxt/package.json": '{ "name": "nuxt", "version": "4.999.0" }\n',
  ".nuxt/routes.ts": 'export const routeName = "index";\n\nexport const unusedGenerated = 0;\n',
  "util.ts": "export const used = 1;\n\nexport const unusedWritten = 2;\n",
  "pages/index.ts":
    'import { routeName } from "../.nuxt/routes.js";\nimport { used } from "../util.js";\n\nconsole.log(routeName, used);\n',
};

const roots: string[] = [];
afterAll(() => {
  for (const root of roots) {
    rmSync(root, { recursive: true, force: true });
  }
});

/** The project analyzed with `analysis.generated_files` set to one value; the framework package itself is unused. */
function analyzed(generatedFiles: "exclude" | "include"): ReturnType<typeof emitterInputOf> {
  const root = writeProject(PROJECT);
  roots.push(root);
  const repository = JSON.stringify({
    target: { kind: "application" },
    analysis: { generated_files: generatedFiles },
  });
  const { config } = resolve({ repository: { text: repository, label: "deadset.json" } });
  return emitterInputOf(root, config);
}

describe("the generated-file class", () => {
  it("retains each declaration below a directory an applied row names as generated, and reports the one beside it", () => {
    const input = analyzed("exclude");

    expect(
      findingsOf(input)
        .filter((finding) => finding.code !== "DS1701")
        .map((finding) => `${finding.code} ${finding.symbol.name}`),
    ).toEqual(["DS1001 unusedWritten"]);
    expect(
      input.swept.sweep.retained.map(
        (record) =>
          `${record.class} ${record.site.path}:${String(record.site.line)} ${record.detail}`,
      ),
    ).toEqual([
      "generated-file .nuxt/routes.ts:1 generated below a directory the convention row nuxt names",
    ]);
  });

  it("reports a declaration in a generated file once generated files are included, marked as one no edit may act on", () => {
    const found = findingsOf(analyzed("include"))
      .filter((finding) => finding.code !== "DS1701")
      .map(
        ({ code, symbol, generated, fixability }) =>
          `${code} ${symbol.name} generated=${String(generated)} ${fixability}`,
      );

    expect(found).toEqual([
      "DS1001 unusedGenerated generated=true none",
      "DS1001 unusedWritten generated=false deletable",
    ]);
  });
});

describe("an export a generated file references only inside itself", () => {
  /** The redundant-export findings of a project whose generated file reads its own export. */
  function redundantExports(generatedFiles: "exclude" | "include"): readonly string[] {
    const root = writeProject({
      "package.json": '{ "name": "@example/app", "type": "module", "main": "./main.ts" }\n',
      "schema_pb.ts":
        "// @generated by the schema compiler\n\nexport const inner = 1;\n\nexport const outer = inner + 1;\n",
      "main.ts": 'import { outer } from "./schema_pb.js";\n\nconsole.log(outer);\n',
    });
    roots.push(root);
    const { config } = resolve({
      repository: {
        text: JSON.stringify({
          target: { kind: "application" },
          analysis: { generated_files: generatedFiles },
        }),
        label: "deadset.json",
      },
    });
    return findingsOf(emitterInputOf(root, config))
      .filter((finding) => finding.code === "DS1503")
      .map(({ symbol, generated }) => `${symbol.name} generated=${String(generated)}`);
  }

  it("is not reported as a redundant export keyword under the default", () => {
    expect(redundantExports("exclude")).toEqual([]);
  });

  it("is reported as one, marked generated, once generated files are included", () => {
    expect(redundantExports("include")).toEqual(["inner generated=true"]);
  });
});

describe("the mark a file's leading comments make", () => {
  it("reads the header line in a line comment or a block comment before the first token, at its line", () => {
    expect(
      [
        "// Code generated by protoc-gen-es. DO NOT EDIT.\nexport {};\n",
        "#!/usr/bin/env node\n// Code generated by a tool. DO NOT EDIT.\r\nexport {};\n",
        "/* eslint-disable */\n/*\n// Code generated by a tool. DO NOT EDIT.\n*/\nexport {};\n",
      ].map(generatedMark),
    ).toEqual([
      { evidence: "header", line: 1, detail: "// Code generated by protoc-gen-es. DO NOT EDIT." },
      { evidence: "header", line: 2, detail: "// Code generated by a tool. DO NOT EDIT." },
      { evidence: "header", line: 3, detail: "// Code generated by a tool. DO NOT EDIT." },
    ]);
  });

  it("reads the @generated tag as a word of a leading comment, at the line holding it", () => {
    expect(
      [
        "/**\n * @generated SignedSource<<0>>\n */\nexport {};\n",
        "// @generated\n",
        "// @generated",
        "\uFEFF#!/usr/bin/env node\n// @generated\n",
        "/*/ @generated */\nexport {};\n",
      ].map(generatedMark),
    ).toEqual([
      { evidence: "tag", line: 2, detail: " * @generated SignedSource<<0>>" },
      { evidence: "tag", line: 1, detail: "// @generated" },
      { evidence: "tag", line: 1, detail: "// @generated" },
      { evidence: "tag", line: 2, detail: "// @generated" },
      { evidence: "tag", line: 1, detail: "/*/ @generated */" },
    ]);
  });

  it("reads a generator's notice across the leading comments at the first line holding either word, or a first line naming the tool", () => {
    expect(
      [
        "// Code generated by a tool. Do not edit.\n",
        "/* eslint-disable */\n// This file was automatically generated by a router.\n// You should NOT make any changes in this file as it will be overwritten.\nexport {};\n",
        "/* AUTO-GENERATED FILE. DO NOT EDIT. */\nexport {};\n",
        "// Generated by a-bundler v1.0.0\nexport {};\n",
        "// Bundle constants.\n// This file is generated by the bundler;\n// do not edit it by hand.\n",
      ].map(generatedMark),
    ).toEqual([
      { evidence: "notice", line: 1, detail: "// Code generated by a tool. Do not edit." },
      {
        evidence: "notice",
        line: 2,
        detail: "// This file was automatically generated by a router.",
      },
      { evidence: "notice", line: 1, detail: "/* AUTO-GENERATED FILE. DO NOT EDIT. */" },
      { evidence: "notice", line: 1, detail: "// Generated by a-bundler v1.0.0" },
      { evidence: "notice", line: 2, detail: "// This file is generated by the bundler;" },
    ]);
  });

  it("marks nothing for a mark after the first token, a header that differs, or a longer tag", () => {
    expect(
      [
        "export {};\n// Code generated by a tool. DO NOT EDIT.\n",
        "// @generatedBy a tool\n",
        "// email@generated.example\n",
        "const tag = '@generated';\n",
        "// A note.\nexport {};\n// @generated\n",
        "/* A note. */\nexport {};\n// @generated\n",
        "export const a = 1; /* @generated */\n",
        "// Generated files go to dist/.\nexport {};\n",
        "/* Edit with care: generated values below. */\nexport {};\n",
        "// A note.\n// Generated by a tool\n",
      ].map(generatedMark),
    ).toEqual(Array(10).fill(undefined));
  });

  it("marks nothing past a block comment left open, though its opening reads as a close", () => {
    expect(generatedMark("//*\n/*/ // @generated\n")).toBeUndefined();
  });
});

describe("a file whose leading comments mark it generated", () => {
  it("retains its declarations, names the mark, and reports one past the first token", () => {
    const root = writeProject({
      "package.json": '{ "name": "@example/app", "type": "module", "main": "./main.ts" }\n',
      "wire.ts":
        "// Code generated by a tool. DO NOT EDIT.\n\nexport const usedWire = 1;\n\nexport const unusedWire = 2;\n",
      "tagged.ts": "/** @generated */\nexport const usedTag = 1;\n\nexport const unusedTag = 2;\n",
      "late.ts":
        "export const usedLate = 1;\n\n// Code generated by a tool. DO NOT EDIT.\nexport const unusedLate = 2;\n",
      "main.ts":
        'import { usedLate } from "./late.js";\nimport { usedTag } from "./tagged.js";\nimport { usedWire } from "./wire.js";\n\nconsole.log(usedLate, usedTag, usedWire);\n',
    });
    roots.push(root);
    const { config } = resolve({
      repository: {
        text: JSON.stringify({ target: { kind: "application" } }),
        label: "deadset.json",
      },
    });
    const input = emitterInputOf(root, config);

    expect(findingsOf(input).map((finding) => `${finding.code} ${finding.symbol.name}`)).toEqual([
      "DS1001 unusedLate",
    ]);
    expect(
      input.swept.sweep.retained.map(
        (record) => `${record.class} ${record.site.path} ${record.detail}`,
      ),
    ).toEqual([
      "generated-file tagged.ts generated by the @generated tag its leading comments hold",
      "generated-file wire.ts generated by the header line its leading comments hold",
    ]);
  });

  it("reports what only its top-level code calls where nothing imports it", () => {
    const root = writeProject({
      "package.json": '{ "name": "@example/app", "type": "module", "main": "./main.ts" }\n',
      "wire.ts": '// @generated\nimport { helper } from "./util.js";\n\nhelper();\n',
      "util.ts": "export function helper(): void {}\n",
      "main.ts": "console.log(1);\n",
    });
    roots.push(root);
    const { config } = resolve({
      repository: {
        text: JSON.stringify({ target: { kind: "application" } }),
        label: "deadset.json",
      },
    });

    expect(
      findingsOf(emitterInputOf(root, config)).map(
        (finding) => `${finding.code} ${finding.symbol.name}`,
      ),
    ).toEqual(["DS1001 helper", "DS1602 util.ts", "DS1602 wire.ts"]);
  });
});

describe("the generator row a generated file matches", () => {
  const engine = openEngine({ collectTiming: false });
  const matched = (text: string): ReturnType<typeof generatorOf> =>
    generatorOf(engine.parseSourceFile("/project/gen.ts", text));
  const TS_PROTO = (version: string): string =>
    `// Code generated by protoc-gen-ts_proto. DO NOT EDIT.\n// versions:\n//   protoc-gen-ts_proto  ${version}\n//   protoc               v7.36.2\n// source: v1/service.proto\n\n`;

  it.each([
    [
      "protoc-gen-es inside its interval",
      '// @generated by protoc-gen-es v2.16.0 with parameter "target=ts"\n// @generated from file v1/b.proto (package v1, syntax proto3)\n// @generated from file v1/a.proto (package v1, syntax proto3)\nexport {};\n',
      { row: "protoc-gen-es-2", version: "v2.16.0", schemaFiles: ["v1/a.proto", "v1/b.proto"] },
    ],
    [
      "protoc-gen-es of major 2 outside its interval",
      "// @generated by protoc-gen-es v2.9.0\n// @generated from file v1/a.proto (package v1, syntax proto3)\nexport {};\n",
      { row: "protoc-gen-es-2-fallback", version: "v2.9.0", schemaFiles: ["v1/a.proto"] },
    ],
    [
      "protoc-gen-es of major 1",
      '// @generated by protoc-gen-es v1.10.0 with parameter "target=ts"\n// @generated from file v1/a.proto (package v1, syntax proto3)\nexport {};\n',
      { row: "protoc-gen-es-1", version: "v1.10.0", schemaFiles: ["v1/a.proto"] },
    ],
    [
      "protoc-gen-es of a major no row supports",
      "// @generated by protoc-gen-es v0.5.0\n// @generated from file v1/a.proto (package v1, syntax proto3)\nexport {};\n",
      { row: "protoc-gen-es-unsupported", version: "v0.5.0", schemaFiles: ["v1/a.proto"] },
    ],
    [
      "protoc-gen-connect-es",
      '// @generated by protoc-gen-connect-es v1.6.1 with parameter "target=ts"\n// @generated from file v1/a.proto (package v1, syntax proto3)\nexport {};\n',
      { row: "protoc-gen-connect-es-1", version: "v1.6.1", schemaFiles: ["v1/a.proto"] },
    ],
    [
      "ts-proto with outputSchema",
      `${TS_PROTO("v2.15.0")}import type { FileDescriptorProto } from "ts-proto-descriptors";\n`,
      { row: "ts-proto-2-output-schema", version: "v2.15.0", schemaFiles: ["v1/service.proto"] },
    ],
    [
      "ts-proto writing a service name",
      `${TS_PROTO("v2.15.0")}export const PingServiceServiceName = "v1.PingService";\n`,
      { row: "ts-proto-2", version: "v2.15.0", schemaFiles: ["v1/service.proto"] },
    ],
    [
      "ts-proto writing a service path member",
      `${TS_PROTO("v2.15.0")}export const PingService = { ping: { path: "/v1.PingService/Ping" } };\n`,
      { row: "ts-proto-2", version: "v2.15.0", schemaFiles: ["v1/service.proto"] },
    ],
    [
      "ts-proto writing no service path",
      `${TS_PROTO("v2.15.0")}export const path = { path: "not/a/service" };\nlet OtherServiceName = "v1.Other";\n`,
      { row: "ts-proto-2-types", version: "v2.15.0", schemaFiles: ["v1/service.proto"] },
    ],
    [
      "ts-proto outside the interval",
      `${TS_PROTO("v2.20.0")}export const PingServiceServiceName = "v1.PingService";\n`,
      { row: "ts-proto-2-fallback", version: "v2.20.0", schemaFiles: ["v1/service.proto"] },
    ],
    [
      "protoc-gen-js",
      "// GENERATED CODE -- DO NOT EDIT!\n// source: v1/a.proto\nexport {};\n",
      { row: "protoc-gen-js", schemaFiles: ["v1/a.proto"] },
    ],
    [
      "protoc-gen-grpc-web",
      "// Code generated by protoc-gen-grpc-web. DO NOT EDIT.\n// versions:\n// \tprotoc-gen-grpc-web v1.5.0\n// source: v1/a.proto\nexport {};\n",
      { row: "protoc-gen-grpc-web", version: "v1.5.0", schemaFiles: ["v1/a.proto"] },
    ],
    [
      "protobuf-ts",
      '// @generated by protobuf-ts 2.9.4 with parameter long_type_string\n// @generated from protobuf file "v1/a.proto" (package "v1", syntax proto3)\nexport {};\n',
      { row: "protobuf-ts", version: "2.9.4", schemaFiles: ["v1/a.proto"] },
    ],
    [
      "ts-protoc-gen",
      "// package: v1\n// file: v1/a.proto\nexport {};\n",
      { row: "ts-protoc-gen", schemaFiles: ["v1/a.proto"] },
    ],
  ])("reads %s", (_label, text, want) => {
    expect(matched(text)).toEqual(want);
  });

  it("matches no row where no header is a row's, or the header is after the first token", () => {
    expect(matched("// @generated by a router\nexport {};\n")).toBeUndefined();
    expect(matched("export {};\n// @generated by protoc-gen-es v2.16.0\n")).toBeUndefined();
  });

  it("names no schema file a source line names outside the schema language", () => {
    expect(
      matched("// GENERATED CODE -- DO NOT EDIT!\n// source: v1/a.json\nexport {};\n"),
    ).toEqual({
      row: "protoc-gen-js",
      schemaFiles: [],
    });
  });
});
